pub(super) fn animation(element: &str) -> bool {
    matches!(
        element,
        "animate" | "animateTransform" | "animateMotion" | "set"
    )
}

pub(super) fn kind(element: &str, name: &str) -> Option<Kind> {
    use Kind::*;
    let common = match name {
        "id" => Some(Id),
        "class" | "lang" | "systemLanguage" | "role" | "requiredFeatures"
        | "requiredExtensions" => Some(Text),
        "externalResourcesRequired" => Some(Enum("true|false")),
        "focusable" => Some(Enum("true|false|auto")),
        "tabindex" => Some(Integer),
        "aria-label" => Some(Text),
        "aria-labelledby" | "aria-describedby" => Some(IdList),
        "aria-hidden" => Some(Enum("true|false")),
        _ => None,
    };
    if common.is_some() {
        return common;
    }
    if animation(element) {
        return Some(match name {
            "href" => Href,
            "attributeName" if element != "animateMotion" => AttributeName,
            "attributeType" if element != "animateMotion" => Enum("auto|CSS|XML"),
            "begin" | "end" => Timing,
            "dur" | "min" | "max" | "repeatDur" => Clock,
            "repeatCount" => Repeat,
            "fill" => Enum("freeze|remove"),
            "restart" => Enum("always|whenNotActive|never"),
            "calcMode" if element != "set" => Enum("discrete|linear|paced|spline"),
            "additive" if element != "set" => Enum("replace|sum"),
            "accumulate" if element != "set" => Enum("none|sum"),
            "keyTimes" | "keyPoints" if element != "set" => KeyTimes,
            "keySplines" if element != "set" => KeySplines,
            "from" | "by" if element != "set" => AnimatedValue,
            "to" => AnimatedValue,
            "values" if element != "set" => AnimatedValues,
            "type" if element == "animateTransform" => Enum("translate|scale|rotate|skewX|skewY"),
            "path" if element == "animateMotion" => Path,
            "rotate" if element == "animateMotion" => MotionRotate,
            "origin" if element == "animateMotion" => Enum("default"),
            _ => return None,
        });
    }
    if let Some((_, kind)) = PRESENTATION
        .iter()
        .find(|(attribute, _)| *attribute == name)
    {
        return Some(*kind);
    }
    Some(match (element, name) {
        ("svg", "version" | "baseProfile") => Text,
        ("filter", "filterRes") => PositiveNumbers,
        ("svg" | "symbol" | "view" | "marker" | "pattern", "viewBox") => ViewBox,
        ("svg" | "symbol" | "view" | "marker" | "pattern" | "feImage", "preserveAspectRatio") => {
            AspectRatio
        }
        ("svg" | "use" | "rect" | "pattern" | "mask" | "filter", "x" | "y") => Length,
        ("svg" | "use" | "rect" | "pattern" | "mask" | "filter", "width" | "height") => {
            PositiveLength
        }
        ("rect", "rx" | "ry") | ("ellipse", "rx" | "ry") => PositiveLength,
        ("circle" | "ellipse" | "radialGradient", "cx" | "cy") => Length,
        ("circle" | "radialGradient", "r") | ("radialGradient", "fr") => PositiveLength,
        ("radialGradient", "fx" | "fy") => Length,
        ("line" | "linearGradient", "x1" | "y1" | "x2" | "y2") => Length,
        ("polygon" | "polyline", "points") => Points,
        ("path", "d") => Path,
        (
            "path" | "rect" | "circle" | "ellipse" | "line" | "polygon" | "polyline",
            "pathLength",
        ) => Nonnegative,
        ("text" | "tspan", "x" | "y" | "dx" | "dy") => Lengths,
        ("text" | "tspan", "rotate") => Numbers,
        ("text" | "tspan" | "textPath", "textLength") => PositiveLength,
        ("text" | "tspan" | "textPath", "lengthAdjust") => Enum("spacing|spacingAndGlyphs"),
        ("textPath", "startOffset") => Length,
        ("textPath", "method") => Enum("align|stretch"),
        ("textPath", "spacing") => Enum("auto|exact"),
        ("textPath", "side") => Enum("left|right"),
        ("textPath", "path") => Path,
        (
            "a" | "use" | "textPath" | "mpath" | "linearGradient" | "radialGradient" | "pattern"
            | "feImage",
            "href",
        ) => Href,
        ("a", "target") => Enum("_self"),
        ("linearGradient" | "radialGradient", "gradientUnits")
        | ("pattern", "patternUnits" | "patternContentUnits")
        | ("clipPath", "clipPathUnits")
        | ("mask", "maskUnits" | "maskContentUnits")
        | ("filter", "filterUnits" | "primitiveUnits") => Enum("userSpaceOnUse|objectBoundingBox"),
        ("linearGradient" | "radialGradient", "gradientTransform")
        | ("pattern", "patternTransform") => Transform,
        ("linearGradient" | "radialGradient", "spreadMethod") => Enum("pad|reflect|repeat"),
        ("stop", "offset") => PositiveLength,
        ("marker", "markerWidth" | "markerHeight") => PositiveLength,
        ("marker" | "symbol", "refX" | "refY") => Length,
        ("marker", "markerUnits") => Enum("strokeWidth|userSpaceOnUse"),
        ("marker", "orient") => Orient,
        (element, "x" | "y" | "width" | "height") if FILTER_REGION.contains(&element) => Length,
        (element, "in") if FILTER_INPUT.contains(&element) => Identifier,
        ("feBlend" | "feComposite" | "feDisplacementMap", "in2") => Identifier,
        (element, "result") if FILTER_REGION.contains(&element) => Identifier,
        ("feBlend", "mode") => Enum(
            "normal|multiply|screen|darken|lighten|overlay|color-dodge|color-burn|hard-light|soft-light|difference|exclusion|hue|saturation|color|luminosity",
        ),
        ("feColorMatrix", "type") => Enum("matrix|saturate|hueRotate|luminanceToAlpha"),
        ("feColorMatrix", "values") => Numbers,
        ("feComposite", "operator") => Enum("over|in|out|atop|xor|arithmetic|lighter"),
        ("feComposite", "k1" | "k2" | "k3" | "k4") => Number,
        ("feConvolveMatrix", "order") => PositiveNumbers,
        ("feConvolveMatrix", "kernelMatrix") => Numbers,
        ("feConvolveMatrix", "divisor" | "bias") => Number,
        ("feConvolveMatrix", "targetX" | "targetY") => Integer,
        ("feConvolveMatrix", "edgeMode") | ("feGaussianBlur", "edgeMode") => {
            Enum("duplicate|wrap|none")
        }
        ("feConvolveMatrix", "preserveAlpha") => Enum("true|false"),
        ("feConvolveMatrix" | "feDiffuseLighting" | "feSpecularLighting", "kernelUnitLength") => {
            PositiveNumbers
        }
        ("feDiffuseLighting" | "feSpecularLighting", "surfaceScale") => Number,
        ("feDiffuseLighting", "diffuseConstant")
        | ("feSpecularLighting", "specularConstant" | "specularExponent") => Nonnegative,
        ("feDisplacementMap", "scale") => Number,
        ("feDisplacementMap", "xChannelSelector" | "yChannelSelector") => Enum("R|G|B|A"),
        ("feDistantLight", "azimuth" | "elevation") => Number,
        ("fePointLight" | "feSpotLight", "x" | "y" | "z") => Number,
        (
            "feSpotLight",
            "pointsAtX" | "pointsAtY" | "pointsAtZ" | "specularExponent" | "limitingConeAngle",
        ) => Number,
        ("feDropShadow" | "feOffset", "dx" | "dy") => Number,
        ("feDropShadow" | "feGaussianBlur", "stdDeviation") => PositiveNumbers,
        ("feMorphology", "operator") => Enum("erode|dilate"),
        ("feMorphology", "radius") => PositiveNumbers,
        ("feTurbulence", "baseFrequency") => PositiveNumbers,
        ("feTurbulence", "numOctaves") => PositiveInteger,
        ("feTurbulence", "seed") => Number,
        ("feTurbulence", "stitchTiles") => Enum("stitch|noStitch"),
        ("feTurbulence", "type") => Enum("fractalNoise|turbulence"),
        ("feFuncA" | "feFuncB" | "feFuncG" | "feFuncR", "type") => {
            Enum("identity|table|discrete|linear|gamma")
        }
        ("feFuncA" | "feFuncB" | "feFuncG" | "feFuncR", "tableValues") => Numbers,
        (
            "feFuncA" | "feFuncB" | "feFuncG" | "feFuncR",
            "slope" | "intercept" | "amplitude" | "exponent" | "offset",
        ) => Number,
        _ => return None,
    })
}

